"""Renders `docs/EVAL_REPORT.md` -- the core development feedback loop.

Written in the order `.claude/skills/run-eval` says to read it: per-code recall
first, confounder false positives second, precision at depth third, budget and
runtime last. A code sitting at 0% recall is the most expensive bug this project
can have, so it is the first thing on the page and it is called a bug in the
text rather than left for the reader to infer.
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

from .harness import PLANNED, PRECISION_AT, EvalReport

__all__ = ["PLANNED", "REPORT_PATH", "render", "summary_rows", "write"]

REPORT_PATH = "docs/EVAL_REPORT.md"

FAMILY_NAMES = {
    "A": "Entitlement / policy violations",
    "B": "Compensation outliers vs peer group",
    "C": "Identity and payroll fraud",
    "D": "Behavioural / temporal drift",
}


def _pct(value: float | None) -> str:
    return "--" if value is None else f"{value * 100:.1f}%"


def _sar(value: float) -> str:
    return f"{value:,.0f}"


def render(report: EvalReport) -> str:
    """The whole report as Markdown."""
    lines: list[str] = []
    add = lines.append

    add("# EVAL_REPORT.md")
    add("")
    add(
        "Generated by `python tasks.py eval --scale "
        f"{report.scale}`. Because the anomalies were injected, every figure "
        "here is exact rather than estimated."
    )
    add("")
    add(f"- **Scale** {report.scale} ({report.employees:,} employees)")
    add(f"- **Run** `{report.run_id}`")
    add(f"- **Generated** {datetime.now(UTC).strftime('%Y-%m-%dT%H:%M:%SZ')}")
    add(f"- **Rule pack** `{report.rule_digest}`")
    add(
        "- **Detectors built** "
        f"{len(report.implemented)} of {len(report.codes)} codes"
    )
    add("")

    if report.warnings:
        add("> **Warnings**")
        for warning in report.warnings:
            add(f"> - {warning}")
        add("")

    # ---------------------------------------------------------------- 1
    add("## 1. Per-anomaly-code recall")
    add("")
    add(
        "One row per code. **A code with a detector sitting at 0% recall is a "
        "bug, not a tuning problem** -- the injector and the detector disagree "
        "about what the code means, and both are defined side by side in "
        "`docs/ANOMALY_CATALOG.md`. Reconcile them there first."
    )
    add("")
    add(
        "`Window` is the share of found cases whose detected period range "
        "overlaps the injected one -- whether the detector also dated the "
        "finding correctly, not just whom it landed on."
    )
    add("")
    for letter in "ABCD":
        rows = report.family(letter)
        if not rows:
            continue
        recall = report.family_recall(letter)
        precision = report.family_precision(letter)
        built = [r for r in rows if r.built]
        add(f"### Family {letter} -- {FAMILY_NAMES[letter]}")
        add("")
        add(
            f"Recall {_pct(recall)} | precision {_pct(precision)} "
            f"| measured over the {len(built)} of {len(rows)} codes that have a "
            "detector"
        )
        add("")
        add("| Code | Detector | Injected | Found | Recall | Windows | Precision | Window |")
        add("|---|---|---:|---:|---:|---:|---:|---:|")
        for row in rows:
            add(
                f"| {row.code} | {row.detector} | {row.injected} | {row.detected} "
                f"| {_pct(row.recall)} | {row.hits} | {_pct(row.precision)} "
                f"| {_pct(row.window_rate)} |"
            )
        add("")

    if report.zero_recall:
        add(
            "**Zero-recall codes with a detector: "
            + ", ".join(r.code for r in report.zero_recall)
            + ".** Fix the definition mismatch; do not lower a threshold."
        )
        add("")

    # ---------------------------------------------------------------- 2
    add("## 2. Confounder false positives")
    add("")
    add(
        "Planted legitimate oddities -- senior specialists near the top of the "
        "band, salary jumps *with* a promotion record, spousal shared accounts, "
        "quiet field roles. **None may be scored CRITICAL.** A detector that "
        "flags everything scores 100% recall and is useless to a reviewer."
    )
    add("")
    add("| Confounder | Tests | Planted | Flagged | By its own code | CRITICAL | HIGH | Codes fired |")
    add("|---|---|---:|---:|---:|---:|---:|---|")
    for row in report.confounders:
        add(
            f"| `{row.confounder_type}` | {row.confounds_code} | {row.planted} "
            f"| {row.flagged_any} | {row.flagged_by_its_code} "
            f"| {row.flagged_critical} | {row.flagged_high} "
            f"| {', '.join(row.codes_fired) or '--'} |"
        )
    add("")
    critical = [r for r in report.confounders if r.flagged_critical]
    high = [r for r in report.confounders if r.flagged_high]
    if critical:
        add(
            f"**{len(critical)} confounder type(s) reached CRITICAL: "
            + ", ".join(f"`{r.confounder_type}`" for r in critical)
            + ".** Each is a missing exclusion, not a threshold to lower."
        )
    elif high:
        add(
            f"**No confounder reached CRITICAL; {len(high)} reached HIGH: "
            + ", ".join(f"`{r.confounder_type}`" for r in high)
            + ".**"
        )
    else:
        add("**No confounder reached CRITICAL or HIGH.**")
    add("")

    # ---------------------------------------------------------------- 2b
    if report.cohorts is not None:
        cohorts = report.cohorts
        add("## 2b. What layer 2 compared against")
        add("")
        add(
            "Every peer comparison names the cohort it was made against, and "
            "the cohort is built by walking the fallback ladder in "
            "`policy/fusion.yaml` until it reaches "
            f"{cohorts.min_size} peers. **Heavy reliance on the last rung means "
            "the cohort design is wrong**, not that the detector is: a "
            "comparison against everyone at one grade is a weak comparison."
        )
        add("")
        add("| Rung | Cohort key | Employees | Share |")
        add("|---:|---|---:|---:|")
        total = sum(cohorts.by_level.values()) or 1
        for level, name in enumerate(cohorts.levels, start=1):
            count = cohorts.by_level.get(level, 0)
            add(f"| {level} | `{name}` | {count:,} | {count / total * 100:.1f}% |")
        add("")
        add(
            f"{cohorts.below_min:,} employees "
            f"({cohorts.below_min / total * 100:.1f}%) reach the last rung with "
            f"fewer than {cohorts.min_size} peers -- for those the cohort is "
            "reported as context in the evidence and is never the trigger."
        )
        add("")
        if report.salary is not None:
            salary = report.salary
            add(
                "The expected-salary model was fitted over "
                f"{salary.rows:,} employees on "
                f"{', '.join(salary.drivers)}; attribution method "
                f"`{salary.method}`; median gap between actual and expected "
                f"pay **SAR {_sar(salary.median_abs_residual)}** a month."
            )
            add("")

    # ---------------------------------------------------------------- 2c
    if report.graph is not None or report.ml is not None:
        add("## 2c. What layer 3 looked at")
        add("")
    if report.graph is not None:
        graph = report.graph
        add(
            "The graph checks find their candidates set-based in DuckDB and "
            "hand only the candidate subgraphs to `networkx`. The number that "
            "matters here is **linked employees**: that is the size of the "
            "graph actually held in memory, and it must stay a tiny fraction "
            "of the workforce at every scale."
        )
        add("")
        add("| | Count |")
        add("|---|---:|")
        add(f"| Employees sharing a bank account or an identity number "
            f"| {graph.graph_nodes:,} |")
        add(f"| Components resolved | {graph.components:,} |")
        add(f"| Largest component | {graph.largest_component:,} |")
        for name in sorted(graph.by_class):
            add(f"| — classified `{name}` | {graph.by_class[name]:,} |")
        add(f"| Manager-cycle candidates walked | {graph.cycle_candidates:,} |")
        add(f"| Manager cycles found | {graph.cycles_found:,} |")
        add(f"| Self-approved assignment records | {graph.self_approvals:,} |")
        add("")
        add(
            "A component classified `spousal` or `near_duplicate` is not a "
            "false positive suppressed by a threshold — each is a *different* "
            "finding: a declared joint account is no finding at all, and a "
            "shared account with a shared date of birth is C06 rather than C01."
        )
        add("")
    if report.ml is not None:
        ml = report.ml
        add(
            "The two unsupervised models produce no anomaly code, so they "
            "cannot appear in the recall table above — but *\"it scored "
            "everybody the same\"* is exactly the failure that table catches "
            "for a rule, so it is measured here instead. **Top-decile recall** "
            "is what a reviewer would meet if they worked only the top tenth "
            "of the model ranking and nothing else."
        )
        add("")
        add("| | Value |")
        add("|---|---:|")
        add(f"| Employees scored | {ml.scored:,} |")
        add(f"| Features in the matrix | {ml.features} |")
        add(f"| Expected anomaly rate used | {ml.contamination * 100:.1f}% |")
        add(f"| Device | `{ml.device}` |")
        add(f"| Median score, injected employees | {ml.labelled_median:.1f} |")
        add(f"| Median score, whole population | {ml.population_median:.1f} |")
        add(f"| Recall in the top 10% | {_pct(ml.top_decile_recall)} |")
        add(f"| Recall in the top 1% | {_pct(ml.top_percent_recall)} |")
        add(f"| Lift over a random tenth | {ml.lift:.1f}× |")
        add("")

    # ---------------------------------------------------------------- 3
    add("## 3. Precision at depth")
    add("")
    add(
        "What a reviewer experiences working down the queue, ranked by "
        "cumulative financial impact. Precision@100 matters most: those are the "
        "alerts somebody opens on Monday morning."
    )
    add("")
    add("| Depth | Precision |")
    add("|---|---:|")
    for k in PRECISION_AT:
        add(f"| @{k} | {_pct(report.precision_at.get(k))} |")
    add("")
    add(
        f"Total findings raised: **{sum(c.hits for c in report.codes):,}**, of "
        f"which **{report.unlabelled_hits:,}** are not accounted for by ground "
        f"truth. Cumulative financial impact: **SAR {_sar(report.impact_total)}**."
    )
    add("")

    # ---------------------------------------------------------------- 4
    add("## 4. Alerts after fusion")
    add("")
    if report.alerts is None:
        add(
            "Layer 4 did not run. Severity below is the severity each detector "
            "declares, which is a starting point rather than an adherence check: "
            "the fused score and the banded queue come from `--stages fusion`."
        )
        add("")
        add("| Severity | Findings | Budget at this scale |")
        add("|---|---:|---:|")
        for severity in ("CRITICAL", "HIGH", "MEDIUM"):
            budget = report.severity_budget.get(severity)
            add(
                f"| {severity} | {report.severity_counts.get(severity, 0):,} "
                f"| {budget:,.0f} |" if budget is not None
                else f"| {severity} | "
                     f"{report.severity_counts.get(severity, 0):,} | -- |"
            )
        add("")
    else:
        queue = report.alerts
        add(
            f"**{queue.findings:,} findings became {queue.alerts:,} alerts** "
            f"({queue.collapse:.2f} findings each, "
            f"{queue.per_1000:.1f} per 1,000 employees). An alert is one "
            "employee and one anomaly code: repeated windows of the same finding "
            "are one case a reviewer works, not several. "
            f"{queue.dropped_low_impact:,} finding(s) were below the money floor "
            f"in `policy/fusion.yaml` and {queue.suppressed:,} were suppressed by "
            "a prior dismissal -- suppressed, not deleted."
        )
        add("")
        add(
            "The budget is capacity, scaled linearly from the 1m reference: it "
            "says how many cases a reviewer can work, and the bands are filled "
            "from the top of the queue until the slots run out. **Precision per "
            "band is the number a reviewer actually feels** -- a CRITICAL band "
            "that is two-thirds right is a worse product than a MEDIUM band that "
            "is two-thirds right, and one overall figure hides which you have."
        )
        add("")
        add("| Severity | Alerts | Budget | Lowest score | Precision "
            "| Confounders | Cumulative impact |")
        add("|---|---:|---:|---:|---:|---:|---:|")
        for band in ("CRITICAL", "HIGH", "MEDIUM", "WATCHLIST"):
            budget = queue.budget.get(band)
            add(
                f"| {band} | {queue.by_severity.get(band, 0):,} "
                + (f"| {budget:,.0f} " if budget else "| -- ")
                + f"| {queue.thresholds.get(band, 0):.0f} "
                f"| {_pct(queue.precision_by_band.get(band))} "
                f"| {queue.confounders_by_band.get(band, 0)} "
                f"| SAR {_sar(queue.impact_by_band.get(band, 0.0))} |"
            )
        add("")
        misses = [b for b, ok in queue.within_budget.items() if not ok]
        add(
            ("**Within budget on every band.**" if not misses
             else "**Outside the budget on " + ", ".join(misses) + ".**")
            + " `Lowest score` is the score at each band boundary this run "
            "produced; it is written into every bundle's `provenance."
            "severity_thresholds`, so a stored alert can be checked against the "
            "bands it was banded under rather than against today's pack."
        )
        add("")
        if queue.critical_confounders:
            add(
                "**Planted confounders reaching CRITICAL: "
                + ", ".join(f"`{name}`" for name in queue.critical_confounders)
                + ".** Each is a missing exclusion, not a threshold to lower."
            )
        else:
            add(
                f"**No planted confounder reached CRITICAL** "
                f"({queue.confounders_by_band.get('CRITICAL', 0)} of the "
                f"{sum(queue.confounders_by_band.values())} that were alerted on "
                "at all)."
            )
        add("")
        add(
            f"Every one of the {queue.validated:,} bundles was validated against "
            "`evidence_v1.json` before it was written; "
            f"{queue.corroborated:,} alert(s) carry more than one contributing "
            "layer, which is what `corroboration_bonus` prices."
        )
        add("")

    # ---------------------------------------------------------------- 5
    add("## 5. Runtime profile")
    add("")
    add("| Stage | Seconds |")
    add("|---|---:|")
    for stage, seconds in report.runtime.items():
        add(f"| {stage} | {seconds:.2f} |")
    add("")
    add(
        "Stages marked `(cached)` were reused from a previous run; the time "
        "shown is what the stage took when it last actually ran."
    )
    add("")
    add("## 6. Policy digest")
    add("")
    add(
        "The pack the ground truth was generated under. A mismatch here means "
        "the detector is being scored against stale labels, and the harness "
        "refuses to run rather than report a wrong number."
    )
    add("")
    add("| Pack | Digest |")
    add("|---|---|")
    for name, digest in sorted(report.policy_digest.items()):
        add(f"| `{name}` | `{digest[:23]}...` |")
    add("")
    return "\n".join(lines) + "\n"


def write(report: EvalReport, path: str | Path = REPORT_PATH) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(report), encoding="utf-8")
    return target


def summary_rows(report: EvalReport) -> list[tuple[str, str]]:
    """The compact form the phase gate prints -- a table, not a log."""
    rows = [
        ("codes with a detector", f"{len(report.implemented)}/{len(report.codes)}"),
        ("family A recall", _pct(report.family_recall("A"))),
        ("family A precision", _pct(report.family_precision("A"))),
        ("family B recall", _pct(report.family_recall("B"))),
        ("family B precision", _pct(report.family_precision("B"))),
        ("family C recall", _pct(report.family_recall("C"))),
        ("family D recall", _pct(report.family_recall("D"))),
        ("precision@100", _pct(report.precision_at.get(100))),
        ("findings raised", f"{sum(c.hits for c in report.codes):,}"),
        ("unaccounted findings", f"{report.unlabelled_hits:,}"),
    ]
    if report.alerts is not None:
        queue = report.alerts
        rows += [
            ("alerts raised", f"{queue.alerts:,}"),
            (
                "queue",
                ", ".join(
                    f"{band} {queue.by_severity.get(band, 0)}"
                    for band in ("CRITICAL", "HIGH", "MEDIUM", "WATCHLIST")
                ),
            ),
            ("precision@CRITICAL", _pct(queue.precision_by_band.get("CRITICAL"))),
            ("bundles validated", f"{queue.validated:,}"),
        ]
    return rows
